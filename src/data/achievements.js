// Reverse map: candidateId -> achievementId required to unlock that candidate.
export const UNLOCK_ACHIEVEMENT_BY_CANDIDATE_ID = Object.freeze(
  ACHIEVEMENTS.reduce((acc, ach) => {
    for (const candId of ach.unlockCandidateIds || []) {
      acc[candId] = ach.id;
    }
    return acc;
  }, /** @type {Record<string, string>} */ ({}))
);

export const ALL_UNLOCKABLE_CANDIDATE_IDS = Object.freeze(
  Object.keys(UNLOCK_ACHIEVEMENT_BY_CANDIDATE_ID)
);
